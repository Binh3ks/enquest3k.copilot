def enrich_week(week_num):
    print('── W%d ──────────────────────────────────────' % week_num)
    data = load_week(week_num)

    # 1. Vocab expansion
    old_count = len(data.get('vocab_tiers', []))
    data['vocab_tiers'] = VOCAB[week_num]
    print('  vocab: %d → %d words' % (old_count, len(data['vocab_tiers'])))

    # 2. PART 2 — numbered, split by tier per session
    for sess_num in [1, 2, 3]:
        new_content = build_part2_content(week_num, sess_num)
        new_title   = build_part2_title(week_num, sess_num)
        _update_part_all_views(data, sess_num, 'PART 2', new_content, new_title)
    print('  PART 2: rewritten (numbered, 7/6/5 words per session, sub-totals)')

    # 3. PART 3 — numbered L1-L5
    week_p3 = PART3.get(week_num, {})
    for sess_num in [1, 2, 3]:
        sess_p3 = week_p3.get(sess_num)
        if sess_p3:
            _update_part_all_views(data, sess_num, 'PART 3', sess_p3)
    print('  PART 3: rewritten (numbered L1-L5 per session)')

    # 4. Save
    save_week(week_num, data)
    print()

