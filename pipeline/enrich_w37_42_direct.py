def _find_part(parts, part_key):
    """Return (index, part_dict) for the part whose title starts with part_key."""
    for i, p in enumerate(parts):
        if p['title'].startswith(part_key):
            return i, p
    return -1, None

def _update_part_in_sessions(sessions_list, sess_num, part_key, new_content, new_title=None):
    """Update content (and optionally title) of a PART in a sessions list."""
    for sess in sessions_list:
        if sess.get('session') == sess_num:
            idx, part = _find_part(sess['parts'], part_key)
            if part is not None:
                part['content'] = new_content
                if new_title:
                    part['title'] = new_title
            break

def _update_part_all_views(data, sess_num, part_key, new_content, new_title=None):
    """Update PART in sessions, sessions_5, sessions_2."""
    for key in ('sessions', 'sessions_5', 'sessions_2'):
        if key in data and isinstance(data[key], list):
            _update_part_in_sessions(data[key], sess_num, part_key, new_content, new_title)

def load_week(week_num):
    path = LESSONS_DIRS[0] / ('W%d.json' % week_num)
    return json.loads(path.read_text(encoding='utf-8'))

def save_week(week_num, data):
    payload = json.dumps(data, ensure_ascii=False, indent=2)
    for d in LESSONS_DIRS:
        path = d / ('W%d.json' % week_num)
        if path.exists():
            path.write_text(payload, encoding='utf-8')
    print('  saved W%d.json (%d chars)' % (week_num, len(payload)))

